export function getVillaById(id: string): Villa | undefined {
  return VILLAS.find((v) => v.id === id || v.slug === id);
}

export function getVillasByDestination(destination: string): Villa[] {
  return VILLAS.filter(
    (v) => v.location.toLowerCase() === destination.toLowerCase() && v.active,
  );
}

export function getReviewsByVilla(villaId: string): Review[] {
  return VILLA_REVIEWS.filter((r) => r.villaId === villaId);
}

export function formatIDR(amount: number): string {
  return new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatDate(date: string | Date): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return new Intl.DateTimeFormat("en-US", {
    weekday: "short",
    year: "numeric",
    month: "short",
    day: "numeric",
  }).format(d);
}

export function formatDateShort(date: string | Date): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(d);
}

export function calculateNights(checkIn: string, checkOut: string): number {
  if (!checkIn || !checkOut) return 0;
  const start = new Date(checkIn);
  const end = new Date(checkOut);
  const diff = Math.round((end.getTime() - start.getTime()) / (1000 * 60 * 60 * 24));
  return diff > 0 ? diff : 0;
}

export function calculateBookingCost(
  pricePerNight: number,
  nights: number,
): { subtotal: number; taxes: number; serviceFee: number; total: number } {
  const subtotal = pricePerNight * nights;
  const serviceFee = Math.round(subtotal * 0.05); // 5% service fee
  const taxes = Math.round(subtotal * 0.11); // 11% tax
  const total = subtotal + serviceFee + taxes;
  return { subtotal, taxes, serviceFee, total };
}

export function generateBookingCode(): string {
  const date = new Date();
  const y = date.getFullYear().toString().slice(-2);
  const m = (date.getMonth() + 1).toString().padStart(2, "0");
  const d = date.getDate().toString().padStart(2, "0");
  const rand = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `BH-${y}${m}${d}-${rand}`;
}
